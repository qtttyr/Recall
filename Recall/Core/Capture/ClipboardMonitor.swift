import AppKit
import Foundation

/// Polls only the pasteboard's change counter. Content is read exclusively
/// after a change, and never for concealed, transient, or excluded sources.
@MainActor
final class ClipboardMonitor {
    private let store: ClipStore
    private let settings: AppSettings
    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var isProcessing = false

    var canRead: (() -> Bool)?
    var onCapture: (() -> Void)?
    var onPermissionLost: (() -> Void)?

    init(store: ClipStore, settings: AppSettings) {
        self.store = store
        self.settings = settings
    }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.35, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func noteExternalWrite() {
        lastChangeCount = NSPasteboard.general.changeCount
    }

    private func poll() {
        settings.clearPauseIfNeeded()
        guard !settings.isCapturePaused, !isProcessing else { return }
        guard canRead?() == true else { return }
        guard !Permissions.isSecureInputEnabled() else { return }

        let pasteboard = NSPasteboard.general
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        if PasteboardWriter.isRecallCopy(pasteboard) { return }
        if isConcealed(pasteboard) { return }

        let frontmost = NSWorkspace.shared.frontmostApplication
        let bundle = frontmost?.bundleIdentifier
        if let bundle, settings.excludedBundleIDs.contains(bundle) { return }
        if bundle == Bundle.main.bundleIdentifier { return }

        guard let candidate = candidate(from: pasteboard, frontmost: frontmost) else { return }
        isProcessing = true

        Task {
            defer { isProcessing = false }
            do {
                if let item = try await store.insert(candidate) {
                    onCapture?()
                    _ = item
                }
                try await store.prune(retentionDays: settings.retentionDays, maxItems: settings.maxItems)
            } catch {
                // A failed write must never interrupt the user's copy.
            }
        }
    }

    private func isConcealed(_ pasteboard: NSPasteboard) -> Bool {
        let types = Set(pasteboard.types ?? [])
        let concealed = [
            NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
            NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
            NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
        ]
        return concealed.contains { types.contains($0) }
    }

    private func candidate(from pasteboard: NSPasteboard, frontmost: NSRunningApplication?) -> ClipCandidate? {
        let sourceApp = frontmost?.localizedName
        let sourceBundle = frontmost?.bundleIdentifier

        // Images win over a textual file path, but not over real text.
        if let data = imageData(from: pasteboard) {
            let ocrText = LocalOCR.extractText(from: data)
            return ClipCandidate(
                kind: .image,
                text: ocrText,
                sourceApp: sourceApp,
                sourceBundle: sourceBundle,
                imageData: data,
                hash: ContentClassifier.hash(kind: .image, text: ocrText, imageData: data)
            )
        }

        if let url = fileURL(from: pasteboard) {
            if let data = imageData(at: url) {
                let ocrText = LocalOCR.extractText(from: data)
                return ClipCandidate(
                    kind: .image,
                    text: ocrText,
                    sourceApp: sourceApp,
                    sourceBundle: sourceBundle,
                    imageData: data,
                    hash: ContentClassifier.hash(kind: .image, text: ocrText, imageData: data)
                )
            }
            let path = url.path
            return ClipCandidate(
                kind: .link,
                text: path,
                sourceApp: sourceApp,
                sourceBundle: sourceBundle,
                imageData: nil,
                hash: ContentClassifier.hash(kind: .link, text: path)
            )
        }

        guard let string = pasteboard.string(forType: .string) else { return nil }
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return nil }

        let kind = ContentClassifier.classify(trimmed)
        return ClipCandidate(
            kind: kind,
            text: trimmed,
            sourceApp: sourceApp,
            sourceBundle: sourceBundle,
            imageData: nil,
            hash: ContentClassifier.hash(kind: kind, text: trimmed)
        )
    }

    private func imageData(from pasteboard: NSPasteboard) -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard let tiff = pasteboard.data(forType: .tiff),
              let representation = NSBitmapImageRep(data: tiff),
              let png = representation.representation(using: .png, properties: [:])
        else { return nil }
        return png
    }

    private func fileURL(from pasteboard: NSPasteboard) -> URL? {
        let options: [NSPasteboard.ReadingOptionKey: Any] = [
            .urlReadingFileURLsOnly: true
        ]
        return pasteboard.readObjects(forClasses: [NSURL.self], options: options)?.first as? URL
    }

    private func imageData(at url: URL) -> Data? {
        guard let image = NSImage(contentsOf: url),
              let tiff = image.tiffRepresentation,
              let representation = NSBitmapImageRep(data: tiff)
        else { return nil }
        return representation.representation(using: .png, properties: [:])
    }
}
